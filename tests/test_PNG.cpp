#include <gtest/gtest.h>

#include "PNG.hpp"

namespace
{
// A complete 1x1 RGBA PNG. Fixture bytes and stored CRCs are independent of
// the parser and CRC implementation under test.
std::vector<uint8_t> makePng()
{
    return {
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
        0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89,
        0x00, 0x00, 0x00, 0x0B, 0x49, 0x44, 0x41, 0x54,
        0x78, 0x9C, 0x63, 0x60, 0x00, 0x02, 0x00, 0x00, 0x05,
        0x00, 0x01, 0x7A, 0x5E, 0xAB, 0x3F,
        0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44,
        0xAE, 0x42, 0x60, 0x82};
}
}  // namespace

TEST(PNGTest, RejectsInvalidSignature)
{
    auto bytes = makePng();
    bytes[0] = 0x00;

    EXPECT_THROW(PNG::fromRaw(bytes), std::runtime_error);
}

TEST(PNGTest, RejectsInvalidIhdrLength)
{
    auto bytes = makePng();
    bytes[11] = 0x0C;

    EXPECT_THROW(PNG::fromRaw(bytes), std::runtime_error);
}

TEST(PNGTest, RejectsNonIhdrFirstChunk)
{
    auto bytes = makePng();
    bytes[12] = 'J';

    EXPECT_THROW(PNG::fromRaw(bytes), std::runtime_error);
}

TEST(PNGTest, RejectsTruncatedIhdrWidth)
{
    auto bytes = makePng();
    bytes.resize(19);

    EXPECT_THROW(PNG::fromRaw(bytes), std::out_of_range);
}
